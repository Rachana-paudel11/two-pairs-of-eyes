export function initLoginScreen(onLoginSuccess) {
  const loginScreen = document.getElementById('login-screen');
  const loginForm = document.getElementById('login-form');
  const errorDiv = document.getElementById('login-error');
  const submitBtn = loginForm.querySelector('.login-btn');
  const toggleBtn = document.getElementById('toggle-mode');
  const playerNameGroup = document.getElementById('playerNameGroup');
  const playerNameInput = document.getElementById('playerName');
  const loginTitle = document.querySelector('.login-title');
  const loginSubtitle = document.querySelector('.login-subtitle');
  const tabLogin = document.getElementById('tab-login');
  const tabRegister = document.getElementById('tab-register');

  const traineeIdGroup = document.getElementById('traineeIdGroup');
  const traineeIdInput = document.getElementById('traineeId');

  // Toggle Mode Function
  const setMode = (mode) => {
    errorDiv.hidden = true;
    errorDiv.className = 'login-error'; // Reset class
    loginForm.dataset.mode = mode;
    
    if (mode === 'register') {
      tabRegister.classList.add('active');
      tabLogin.classList.remove('active');
      loginTitle.innerHTML = 'Create <span class="hero-highlight">Account</span>';
      loginSubtitle.textContent = 'Join the safety simulation program today.';
      playerNameGroup.hidden = false;
      playerNameInput.required = true;
      traineeIdGroup.hidden = true;
      traineeIdInput.required = false;
      submitBtn.innerHTML = '➔ Register';
      toggleBtn.innerHTML = '<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M15 3h4a2 2 0 0 1 2 2v14a2 2 0 0 1-2 2h-4"></path><polyline points="10 17 15 12 10 7"></polyline><line x1="15" y1="12" x2="3" y2="12"></line></svg> Login Instead';
    } else {
      tabLogin.classList.add('active');
      tabRegister.classList.remove('active');
      loginTitle.innerHTML = 'Welcome <span class="hero-highlight">Back</span>';
      loginSubtitle.textContent = 'Sign in to continue your warehouse safety training.';
      playerNameGroup.hidden = true;
      playerNameInput.required = false;
      traineeIdGroup.hidden = false;
      traineeIdInput.required = true;
      submitBtn.innerHTML = '➔ Login';
      toggleBtn.innerHTML = '<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M16 21v-2a4 4 0 0 0-4-4H5a4 4 0 0 0-4 4v2"></path><circle cx="8.5" cy="7" r="4"></circle><line x1="20" y1="8" x2="20" y2="14"></line><line x1="23" y1="11" x2="17" y2="11"></line></svg> Create New Account';
    }
  };

  // Event Listeners for toggle
  toggleBtn.addEventListener('click', (e) => {
    e.preventDefault();
    setMode(loginForm.dataset.mode === 'login' ? 'register' : 'login');
  });

  tabLogin.addEventListener('click', (e) => {
    e.preventDefault();
    setMode('login');
  });

  tabRegister.addEventListener('click', (e) => {
    e.preventDefault();
    setMode('register');
  });

  loginForm.addEventListener('submit', async (e) => {
    e.preventDefault();
    
    const isLogin = loginForm.dataset.mode === 'login';
    const traineeId = traineeIdInput.value.trim();
    const playerName = playerNameInput.value.trim();
    const password = document.getElementById('password').value;

    if (!password || (isLogin && !traineeId) || (!isLogin && !playerName)) {
      showError('Please fill in all required fields.');
      return;
    }

    try {
      submitBtn.disabled = true;
      submitBtn.innerHTML = isLogin ? '➔ AUTHENTICATING...' : '➔ REGISTERING...';
      errorDiv.hidden = true;
      errorDiv.className = 'login-error';

      const endpoint = isLogin ? '/api/auth/login' : '/api/auth/register';
      const body = isLogin 
        ? { traineeId, password } 
        : { name: playerName, password }; // ID is auto-generated by backend now

      const response = await fetch(`http://localhost:5000${endpoint}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(body)
      });

      const data = await response.json();

      if (data.success) {
        if (!isLogin && data.generatedId) {
          // Show the generated ID in a success message before starting
          errorDiv.className = 'login-success';
          errorDiv.innerHTML = `<strong>Registration Successful!</strong><br>Your official Trainee ID is: <span style="font-size:1.2rem; color:var(--c-emerald); letter-spacing:1px; margin-top:5px; display:inline-block;">${data.generatedId}</span><br><small>Please save this ID to log in next time.</small>`;
          errorDiv.hidden = false;
          errorDiv.style.animation = 'loginPopIn 0.3s';
          
          // Delay simulation start so they can read it
          setTimeout(() => {
            if (onLoginSuccess) onLoginSuccess(data.trainee);
            loginScreen.style.opacity = '0';
            setTimeout(() => loginScreen.classList.add('hidden'), 600);
          }, 4500);
        } else {
          // Normal login flow
          if (onLoginSuccess) onLoginSuccess(data.trainee);
          loginScreen.style.opacity = '0';
          setTimeout(() => loginScreen.classList.add('hidden'), 600);
        }
      } else {
        showError(data.error || 'Authentication failed.');
      }
    } catch (err) {
      console.error(err);
      showError('Network error. Is the server running?');
    } finally {
      submitBtn.disabled = false;
      submitBtn.innerHTML = isLogin ? '➔ Login' : '➔ Register';
    }
  });

  function showError(msg) {
    errorDiv.textContent = msg;
    errorDiv.hidden = false;
    // Shake animation
    errorDiv.style.animation = 'none';
    errorDiv.offsetHeight; // trigger reflow
    errorDiv.style.animation = 'loginPopIn 0.3s';
  }
}
